local help

local function Build()
	help = CreateFrame("Frame", "TransmogHubHelp", UIParent, "BasicFrameTemplateWithInset")
	help:SetSize(720, 460)
	help:SetPoint("CENTER", 0, 30)
	help:SetFrameStrata("DIALOG")
	help:SetToplevel(true)
	help:EnableMouse(true)
	help:SetMovable(true)
	help:RegisterForDrag("LeftButton")
	help:SetScript("OnDragStart", help.StartMoving)
	help:SetScript("OnDragStop", help.StopMovingOrSizing)
	tinsert(UISpecialFrames, help:GetName())

	local title = help:CreateFontString(nil, "OVERLAY", "GameFontHighlight")
	title:SetPoint("TOP", 0, -6)
	title:SetText("Transmog Hub — справка")

	help.nav = {}
	for i, section in ipairs(TH.HELP) do
		local b = CreateFrame("Button", nil, help)
		b:SetSize(170, 24)
		b:SetPoint("TOPLEFT", 12, -32 - (i - 1) * 26)
		b.sel = b:CreateTexture(nil, "BACKGROUND")
		b.sel:SetAllPoints()
		b.sel:SetColorTexture(TH:SelColor(0.18))
		b:SetHighlightTexture("Interface\\QuestFrame\\UI-QuestTitleHighlight", "ADD")
		b.text = b:CreateFontString(nil, "OVERLAY", "GameFontNormal")
		b.text:SetPoint("LEFT", 8, 0)
		b.text:SetText(section.title)
		b:SetScript("OnClick", function() TH:OpenHelp(i) end)
		help.nav[i] = b
	end

	local scroll = CreateFrame("ScrollFrame", nil, help, "UIPanelScrollFrameTemplate")
	scroll:SetPoint("TOPLEFT", 196, -32)
	scroll:SetPoint("BOTTOMRIGHT", -32, 42)
	local child = CreateFrame("Frame", nil, scroll)
	child:SetSize(480, 10)
	scroll:SetScrollChild(child)
	help.heading = child:CreateFontString(nil, "OVERLAY", "GameFontNormalLarge")
	help.heading:SetPoint("TOPLEFT", 4, -2)
	help.body = child:CreateFontString(nil, "OVERLAY", "GameFontHighlight")
	help.body:SetPoint("TOPLEFT", help.heading, "BOTTOMLEFT", 0, -10)
	help.body:SetWidth(470)
	help.body:SetJustifyH("LEFT")
	help.body:SetSpacing(3)
	help.scroll, help.child = scroll, child

	local close = CreateFrame("Button", nil, help, "UIPanelButtonTemplate")
	TH.PadButton(close)
	close:SetSize(100, 22)
	close:SetPoint("BOTTOMRIGHT", -12, 12)
	close:SetText(CLOSE or "Закрыть")
	close:SetScript("OnClick", function() help:Hide() end)

	local tourBtn = CreateFrame("Button", nil, help, "UIPanelButtonTemplate")
	TH.PadButton(tourBtn)
	tourBtn:SetSize(190, 22)
	tourBtn:SetPoint("BOTTOMLEFT", 12, 12)
	tourBtn:SetText("Пройти обучение заново")
	tourBtn:SetScript("OnClick", function()
		help:Hide()
		TH:StartTour()
	end)

	local hint = help:CreateFontString(nil, "OVERLAY", "GameFontDisableSmall")
	hint:SetPoint("LEFT", tourBtn, "RIGHT", 10, 0)
	hint:SetText("Справка — кнопка «?» в заголовке окна или /thub help")
end

function TH:OpenHelp(index)
	if not help then Build() end
	index = index or help.index or 1
	help.index = index
	local section = self.HELP[index]
	for i, b in ipairs(help.nav) do b.sel:SetShown(i == index) end
	help.heading:SetText(section.title)
	help.body:SetText(table.concat(section.text, "\n"))
	help.child:SetHeight((help.body:GetStringHeight() or 300) + 40)
	if help.scroll.SetVerticalScroll then help.scroll:SetVerticalScroll(0) end
	if self.db then help:SetScale(self.db.scale or 1) end
	help:Show()
	self:SkinNow(help) -- оформление EllesmereUI: справка строится позже главного окна
end

function TH:ToggleHelp()
	if help and help:IsShown() then help:Hide() else self:OpenHelp() end
end
